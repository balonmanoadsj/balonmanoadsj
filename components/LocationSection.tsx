
import React, { forwardRef, useEffect, useRef, useState } from 'react';
import { MATCH_RESULTS, STANDINGS } from '../constants';
import Chart from 'chart.js/auto';

interface ResultsSectionProps {
    id: string;
}

interface MatchResult {
    home: string;
    visitor: string;
    score: string;
    date: string;
    win?: boolean;
    draw?: boolean;
}

interface StandingRow {
    pos: number;
    team: string;
    pts: number;
    p: number;
    w: number;
    l: number;
}

export const LocationSection = forwardRef<HTMLDivElement, ResultsSectionProps>(({ id }, ref) => {
    const chartRef = useRef<HTMLCanvasElement>(null);
    const chartInstance = useRef<Chart | null>(null);
    
    // State to hold dynamic data
    const [matches, setMatches] = useState<MatchResult[]>(MATCH_RESULTS);
    const [standingsData, setStandingsData] = useState<StandingRow[]>(STANDINGS);
    const [loading, setLoading] = useState(true);

    // Fetch data from the scraped JSON file
    useEffect(() => {
        const fetchData = async () => {
            try {
                // Try to fetch the generated JSON file
                // This file will be generated by the GitHub Action/Script
                const response = await fetch('/data/results.json');
                if (response.ok) {
                    const data = await response.json();
                    if (data.matches && data.matches.length > 0) setMatches(data.matches);
                    if (data.standings && data.standings.length > 0) setStandingsData(data.standings);
                }
            } catch (error) {
                console.log("Using default static data (Scraped data not found)");
            } finally {
                setLoading(false);
            }
        };

        fetchData();
    }, []);

    // Update Chart when standingsData changes
    useEffect(() => {
        if (chartRef.current && !loading) {
            if (chartInstance.current) {
                chartInstance.current.destroy();
            }

            const ctx = chartRef.current.getContext('2d');
            if (ctx) {
                chartInstance.current = new Chart(ctx, {
                    type: 'bar',
                    data: {
                        labels: standingsData.map(s => s.team.replace('AD San Juan', 'ADSJ').substring(0, 10)),
                        datasets: [{
                            label: 'Puntos',
                            data: standingsData.map(s => s.pts),
                            backgroundColor: standingsData.map(s => 
                                s.team.toLowerCase().includes('san juan') ? '#16a34a' : '#e5e7eb'
                            ),
                            hoverBackgroundColor: standingsData.map(s => 
                                s.team.toLowerCase().includes('san juan') ? '#15803d' : '#d1d5db'
                            ),
                            borderRadius: 6,
                            borderSkipped: false,
                            barThickness: 'flex',
                            maxBarThickness: 30,
                        }]
                    },
                    options: {
                        responsive: true,
                        maintainAspectRatio: false,
                        plugins: {
                            legend: { display: false },
                            tooltip: {
                                backgroundColor: '#111827',
                                titleColor: '#fff',
                                bodyColor: '#fff',
                                padding: 12,
                                cornerRadius: 8,
                                displayColors: false,
                                callbacks: {
                                    title: (items) => {
                                        const index = items[0].dataIndex;
                                        return standingsData[index].team;
                                    },
                                    label: (context) => `Puntos: ${context.raw}`
                                }
                            }
                        },
                        scales: {
                            y: {
                                beginAtZero: true,
                                grid: { display: true, color: '#f3f4f6', drawTicks: false },
                                ticks: { font: { family: "'Poppins', sans-serif", size: 11 }, color: '#9ca3af', stepSize: 2 },
                                border: { display: false }
                            },
                            x: {
                                grid: { display: false },
                                ticks: { font: { family: "'Poppins', sans-serif", weight: 'bold', size: 11 }, color: '#4b5563' },
                                border: { display: false }
                            }
                        },
                        animation: { duration: 1000 }
                    }
                });
            }
        }

        return () => {
            if (chartInstance.current) {
                chartInstance.current.destroy();
            }
        };
    }, [standingsData, loading]);

    return (
        <section ref={ref} id={id} className="py-20 bg-white">
            <div className="container mx-auto px-4 sm:px-6">
                 <div className="text-center mb-16">
                    <span className="text-green-600 font-bold tracking-wider uppercase text-sm">Temporada 2025/2026</span>
                    <h2 className="text-3xl md:text-5xl font-black text-gray-900 mt-2">Centro de Resultados</h2>
                    <div className="mt-4 w-24 h-1.5 bg-green-500 mx-auto rounded-full"></div>
                    <p className="mt-4 text-gray-500 text-sm">
                        Datos actualizados automáticamente desde la Federación Navarra
                    </p>
                </div>

                <div className="grid grid-cols-1 lg:grid-cols-2 gap-12">
                    
                    {/* Latest Matches */}
                    <div className="flex flex-col h-full">
                        <h3 className="text-2xl font-bold text-gray-800 mb-6 flex items-center">
                            <span className="w-2 h-8 bg-green-500 rounded-full mr-3"></span>
                            Última Jornada
                        </h3>
                        <div className="space-y-4 flex-grow">
                            {matches.map((match, idx) => (
                                <div key={idx} className="flex items-center justify-between bg-gray-50 p-5 rounded-xl border border-gray-100 hover:shadow-md transition-all duration-300 hover:border-green-100 group">
                                    <div className="flex-1 text-right pr-4">
                                        <span className={`font-bold text-sm md:text-base ${match.win ? 'text-gray-900 group-hover:text-green-700' : 'text-gray-600'}`}>{match.home}</span>
                                    </div>
                                    <div className={`px-4 py-2 rounded-lg font-mono font-bold text-white shadow-sm min-w-[90px] text-center text-lg transform group-hover:scale-105 transition-transform ${match.win ? 'bg-gradient-to-r from-green-500 to-green-600' : match.draw ? 'bg-gradient-to-r from-yellow-400 to-yellow-500' : 'bg-gradient-to-r from-red-500 to-red-600'}`}>
                                        {match.score}
                                    </div>
                                    <div className="flex-1 text-left pl-4">
                                        <span className={`font-bold text-sm md:text-base ${!match.win && !match.draw ? 'text-gray-900 group-hover:text-green-700' : 'text-gray-600'}`}>{match.visitor}</span>
                                    </div>
                                    {/* Date displayed conditionally for mobile */}
                                    <div className="hidden sm:block absolute top-2 right-3 text-[10px] text-gray-400 font-mono">
                                        {match.date}
                                    </div>
                                </div>
                            ))}
                        </div>
                    </div>

                    {/* Standings Chart & Table */}
                    <div className="flex flex-col h-full">
                        <h3 className="text-2xl font-bold text-gray-800 mb-6 flex items-center">
                            <span className="w-2 h-8 bg-green-500 rounded-full mr-3"></span>
                            Clasificación General
                        </h3>
                        
                        {/* Chart Container */}
                        <div className="bg-white p-4 rounded-xl border border-gray-100 shadow-sm mb-6 h-64 relative">
                             <canvas ref={chartRef}></canvas>
                        </div>

                        <div className="overflow-hidden bg-white rounded-xl shadow-lg border border-gray-100">
                            <table className="min-w-full">
                                <thead className="bg-gray-900 text-white">
                                    <tr>
                                        <th className="py-3 px-4 text-left text-xs font-semibold uppercase tracking-wider">Pos</th>
                                        <th className="py-3 px-4 text-left text-xs font-semibold uppercase tracking-wider">Equipo</th>
                                        <th className="py-3 px-4 text-center text-xs font-semibold uppercase tracking-wider">PJ</th>
                                        <th className="py-3 px-4 text-center text-xs font-semibold uppercase tracking-wider">Pts</th>
                                    </tr>
                                </thead>
                                <tbody className="divide-y divide-gray-200">
                                    {standingsData.map((row) => (
                                        <tr key={row.team} className={`${row.team.toLowerCase().includes('san juan') ? 'bg-green-50' : 'bg-white'} hover:bg-gray-50 transition-colors group`}>
                                            <td className="py-3 px-4 whitespace-nowrap">
                                                <span className={`inline-flex items-center justify-center w-6 h-6 rounded-full text-xs font-bold transition-transform group-hover:scale-110 ${row.pos === 1 ? 'bg-green-500 text-white shadow-green-200 shadow-md' : 'bg-gray-200 text-gray-600'}`}>
                                                    {row.pos}
                                                </span>
                                            </td>
                                            <td className={`py-3 px-4 whitespace-nowrap text-sm font-bold ${row.team.toLowerCase().includes('san juan') ? 'text-green-700' : 'text-gray-900'}`}>
                                                {row.team}
                                            </td>
                                            <td className="py-3 px-4 whitespace-nowrap text-center text-sm text-gray-500 font-medium">
                                                {row.p}
                                            </td>
                                            <td className="py-3 px-4 whitespace-nowrap text-center text-sm font-black text-gray-900">
                                                {row.pts}
                                            </td>
                                        </tr>
                                    ))}
                                </tbody>
                            </table>
                        </div>
                    </div>
                </div>
            </div>
        </section>
    );
});
